"""Put a visible "Made with AI assistance" label on the brand kit's presentation images and motion videos.

The Space Apps rules ask that images and videos generated with AI carry a visible watermark. The team designed
the identity (name, historical research, references, sketches, style guide, colours, typography) and Codex
generated the final assets from it. The logo files themselves stay clean so they can be used; the label goes on
the images and videos that present the identity. Each file also records the label in its metadata, and a file
that already has it is skipped, so running this twice changes nothing.
  python web/scripts/label-ai-assets.py <ffmpeg>
Code written with AI assistance (Claude); see AI_USAGE.md.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, PngImagePlugin

ROOT = Path(__file__).resolve().parents[2]
LABEL = "Made with AI assistance"
NOTE = "Made with AI assistance: the SEDNA team's identity (name, research, references, sketches, style guide, colours, typography), generated by Codex. See AI_USAGE.md."
FONT = "C:/Windows/Fonts/segoeui.ttf"
IMAGES = [
    "docs/brand/SEDNA-Identity-Overview.png",
    "docs/brand/motion/preview.png",
    "docs/brand/applications/sedna-presentation-1920x1080.png",
    "docs/brand/applications/sedna-social-1200x630.png",
    "docs/brand/applications/sedna-story-1080x1920.png",
]
VIDEOS = ["docs/brand/motion/arrival", "docs/brand/motion/convergence", "docs/brand/motion/orbital"]


def label_image(path: Path) -> None:
    img = Image.open(path)
    if img.info.get("ai-label"):
        print(f"{path.name}: already labelled")
        return
    img = img.convert("RGBA")
    w, h = img.size
    size = max(14, round(min(w, h) * 0.022))
    font = ImageFont.truetype(FONT, size)
    pad, margin = round(size * 0.55), round(size * 1.2)
    box = ImageDraw.Draw(img).textbbox((0, 0), LABEL, font=font)
    tw, th = box[2] - box[0], box[3] - box[1]
    x1, y1 = w - margin, h - margin
    x0, y0 = x1 - tw - 2 * pad, y1 - th - 2 * pad
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    d.rounded_rectangle((x0, y0, x1, y1), radius=pad, fill=(2, 3, 5, 150))
    d.text((x0 + pad - box[0], y0 + pad - box[1]), LABEL, font=font, fill=(236, 238, 242, 225))
    out = Image.alpha_composite(img, layer)
    meta = PngImagePlugin.PngInfo()
    meta.add_text("ai-label", LABEL)
    meta.add_text("Comment", NOTE)
    out.save(path, pnginfo=meta, optimize=True)
    print(f"{path.name}: labelled ({w} x {h})")


def has_label(ffmpeg: str, path: Path) -> bool:
    probe = subprocess.run([ffmpeg, "-hide_banner", "-i", str(path)], capture_output=True, text=True)
    return "Made with AI assistance" in probe.stderr


def label_video(ffmpeg: str, stem: Path) -> None:
    font = FONT.replace(":", "\\:")
    draw = (f"drawtext=fontfile='{font}':text='{LABEL}':fontsize=22:fontcolor=0xECEEF2@0.9:"
            "box=1:boxcolor=0x020305@0.6:boxborderw=10:x=w-tw-30:y=h-th-30")
    for ext, codec in (("mp4", ["-c:v", "libx264", "-preset", "slow", "-crf", "18", "-pix_fmt", "yuv420p", "-movflags", "+faststart"]),
                       ("webm", ["-c:v", "libvpx-vp9", "-crf", "32", "-b:v", "0", "-pix_fmt", "yuv420p"])):
        src = stem.with_suffix(f".{ext}")
        if has_label(ffmpeg, src):
            print(f"{src.name}: already labelled")
            continue
        tmp = src.with_name(f"{src.stem}.labelled.{ext}")
        subprocess.run([ffmpeg, "-y", "-hide_banner", "-loglevel", "error", "-i", str(src), "-vf", draw, "-an", *codec,
                        "-metadata", f"comment={NOTE}", str(tmp)], check=True)
        tmp.replace(src)
        print(f"{src.name}: labelled")


if __name__ == "__main__":
    ffmpeg = sys.argv[1]
    for rel in IMAGES:
        label_image(ROOT / rel)
    for rel in VIDEOS:
        label_video(ffmpeg, ROOT / rel)
